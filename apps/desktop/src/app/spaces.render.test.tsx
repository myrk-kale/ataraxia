// @vitest-environment jsdom
import { act } from "react";
import { createRoot, type Root } from "react-dom/client";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { handleInsights } from "../dev/insightsMock";
import type { ChatSession } from "../lib/workspace";
import { newBridge } from "./spaceCommands";

(globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }).IS_REACT_ACT_ENVIRONMENT = true;

const calls: { cmd: string; args: Record<string, unknown> | undefined }[] = [];
/** Answers a test wants to force, by command. */
let forced: Record<string, unknown> = {};

vi.mock("@tauri-apps/api/core", () => ({
  invoke: (cmd: string, args?: Record<string, unknown>) => {
    calls.push({ cmd, args });
    if (cmd in forced) {
      return Promise.resolve(forced[cmd]);
    }
    const result = handleInsights(cmd, args, () => undefined);
    return Promise.resolve(result.handled ? result.value : null);
  },
}));
vi.mock("@tauri-apps/api/event", () => ({ listen: () => Promise.resolve(() => undefined) }));

const session = {
  id: "s1",
  repository_id: "r1",
  worktree_id: "w1",
  provider: "fake",
  title: "Chat",
  status: "ready",
} as unknown as ChatSession;

let root: Root;
let host: HTMLDivElement;

async function flush() {
  for (let i = 0; i < 6; i += 1) {
    await act(async () => {
      await Promise.resolve();
      await new Promise((resolve) => setTimeout(resolve, 0));
    });
  }
}

beforeEach(() => {
  calls.length = 0;
  forced = {};
  host = document.createElement("div");
  document.body.appendChild(host);
  root = createRoot(host);
});

afterEach(() => {
  act(() => root.unmount());
  host.remove();
});

describe("spaces render with real data shapes", () => {
  it("Decisions is a list of threads like issues: open first, searchable, one page per decision", async () => {
    const { DecisionsSpace } = await import("../decisions/DecisionsSpace");
    const bridge = { current: newBridge() };
    act(() => root.render(<DecisionsSpace bridge={bridge} session={session} onError={(m) => { throw new Error(m); }} onOpenFile={() => undefined} />));
    await flush();
    // The list, newest first, with who opened each and how long ago.
    const listed = host.textContent ?? "";
    expect(listed).toContain("Open 2");
    expect(listed).toContain("Closed 1");
    expect(listed).toContain("Write the retry helper locally");
    expect(listed).toContain("Store only a hash of issued tokens?");
    expect(listed).not.toContain("Return 202 Accepted");
    expect(listed).toContain("opened 1 day ago by you");
    expect(listed).toContain("claude · sonnet");
    // Nothing was generated by opening the space.
    expect(calls.some((c) => c.cmd === "decisions_generate")).toBe(false);

    // The closed tab and the search.
    const closedTab = [...host.querySelectorAll("[role=tab]")].find((t) => t.textContent?.startsWith("Closed"))!;
    act(() => (closedTab as HTMLButtonElement).click());
    expect(host.textContent).toContain("Return 202 Accepted");
    expect(host.textContent).toContain("approved");
    act(() => (host.querySelector("[role=tab]") as HTMLButtonElement).click());

    // A decision opens on a page that is only its text and, at the bottom, what can be done.
    const row = [...host.querySelectorAll("ul button")].find((b) => b.textContent?.includes("Store only a hash"))!;
    act(() => (row as HTMLButtonElement).click());
    await flush();
    const page = host.textContent ?? "";
    expect(page).toContain("Store only a hash of issued tokens?");
    expect(page).toContain("Tokens are returned once and only their SHA-256 hash is persisted");
    // Nothing else is on the page: no sidebar, no context, no code list, no timeline.
    for (const absent of ["Context", "Alternatives", "Commits", "src/studio/auth/tokens.py", "Why SHA-256 and not a slow hash?", "Request a change"]) {
      expect(page, absent).not.toContain(absent);
    }
    const buttons = [...host.querySelectorAll("form[aria-label='Your verdict'] button")].map((b) => b.textContent?.trim());
    expect(buttons).toEqual(["Comment", "Reject", "Approve"]);
    expect(host.querySelector("textarea[aria-label='Comment']")).not.toBeNull();
    expect(bridge.current.context?.kind).toBe("decision");

    // The thread is a modal with the updates, opened from one quiet button.
    const threadButton = [...host.querySelectorAll("button")].find((b) => b.textContent?.startsWith("Thread"))!;
    expect(threadButton.textContent).toContain("3 updates");
    act(() => (threadButton as HTMLButtonElement).click());
    await flush();
    const modal = document.body.textContent ?? "";
    expect(modal).toContain("Why SHA-256 and not a slow hash?");
    expect(modal).toContain("Hash tokens before storing them");
    expect(modal).toContain("Implements the hashing");
    expect(modal).toContain("Link a commit");
    act(() => {
      document.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true }));
    });
    await flush();

    // A verdict carries the comment typed beside it; a comment alone changes no verdict.
    const box = host.querySelector("textarea[aria-label='Comment']") as HTMLTextAreaElement;
    const type = (value: string) => {
      const setter = Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, "value")!.set!;
      act(() => {
        setter.call(box, value);
        box.dispatchEvent(new Event("input", { bubbles: true }));
      });
    };
    const press = (label: string) =>
      act(() => ([...host.querySelectorAll("form[aria-label='Your verdict'] button")].find((b) => b.textContent?.trim() === label) as HTMLButtonElement).click());
    type("Needs a migration note");
    press("Comment");
    await flush();
    expect(calls.some((c) => c.cmd === "decision_comment" && c.args?.text === "Needs a migration note")).toBe(true);
    expect(calls.some((c) => c.cmd === "decision_set_state")).toBe(false);
    type("Fine by me");
    press("Approve");
    await flush();
    const verdict = calls.find((c) => c.cmd === "decision_set_state")!;
    expect(verdict.args).toMatchObject({ decisionState: "approved", comment: "Fine by me" });
    expect([...host.querySelectorAll("form[aria-label='Your verdict'] button")].map((b) => b.textContent?.trim())).toEqual(["Comment", "Reopen"]);
    expect(host.textContent).toContain("Approved");
    expect(calls.some((c) => c.cmd.startsWith("code_"))).toBe(false);

    // J and K step through the decisions, and Back returns to the list.
    act(() => bridge.current.commands.item?.(-1));
    await flush();
    expect(host.textContent).toContain("2 of 3");
    const back = [...host.querySelectorAll("button")].find((b) => b.textContent?.includes("Decisions"))!;
    act(() => (back as HTMLButtonElement).click());
    expect(host.textContent).toContain("Generate…");
  });

  it("Decisions says nothing was generated until you ask, and generating is a choice of model", async () => {
    forced = { decisions_list: [] };
    const { DecisionsSpace } = await import("../decisions/DecisionsSpace");
    act(() => root.render(<DecisionsSpace bridge={{ current: newBridge() }} session={session} onError={() => undefined} onOpenFile={() => undefined} />));
    await flush();
    expect(host.textContent).toContain("No decisions yet");
    expect(host.textContent).toContain("Nothing is generated until you ask");
    expect(calls.some((c) => c.cmd === "decisions_generate")).toBe(false);

    // Generate asks which changes, which provider and which model before anything is sent.
    const generate = [...host.querySelectorAll("button")].find((b) => b.textContent?.includes("Generate"))!;
    act(() => (generate as HTMLButtonElement).click());
    await flush();
    const dialog = document.body.textContent ?? "";
    expect(dialog).toContain("Generate decisions");
    expect(dialog).toContain("Provider");
    expect(dialog).toContain("Model");
    expect(dialog).toContain("Provider default");
    expect(calls.some((c) => c.cmd === "decisions_generate")).toBe(false);
  });

  it("Decisions explains an empty chat instead of showing nothing", async () => {
    const { DecisionsSpace } = await import("../decisions/DecisionsSpace");
    act(() => root.render(<DecisionsSpace bridge={{ current: newBridge() }} session={null} onError={() => undefined} onOpenFile={() => undefined} />));
    await flush();
    expect(host.textContent).toContain("Open or start a chat");
  });

  it("the shortcut legend and settings render their content", async () => {
    const { ShortcutLegend } = await import("./ShortcutLegend");
    act(() => root.render(<ShortcutLegend isOpen onClose={() => undefined} />));
    await flush();
    expect(document.body.textContent).toContain("Toggle the terminal");
    expect(document.body.textContent).toContain("BTW");
  });

  it("BTW is one wide bar: a placeholder and the choice of model joined to it, and nothing else", async () => {
    const { BtwPalette } = await import("../btw/BtwPalette");
    const providers = [
      { kind: "fake", display_name: "Demo", available: true, detail: null, settings: { models: [{ id: "quick", label: "Quick", efforts: [] }] } },
      { kind: "claude", display_name: "Claude Code", available: true, detail: null, settings: { models: [{ id: "sonnet", label: "Sonnet", efforts: [] }] } },
    ] as never;
    const render = () =>
      act(() =>
        root.render(
          <BtwPalette
            isOpen
            item={{ kind: "file", label: "tokens.py", path: "src/studio/auth/tokens.py", startLine: 6, endLine: 15 }}
            providers={providers}
            resume={null}
            session={session}
            space="code"
            onClose={() => undefined}
            onError={(m) => { throw new Error(m); }}
          />,
        ),
      );
    render();
    await flush();
    const dialog = document.body.querySelector("[role=dialog]")!;
    const input = dialog.querySelector("input[aria-label='Ask about what you are looking at']") as HTMLInputElement;
    expect(input.placeholder).toBe("Ask about what you are looking at…");
    // Nothing is written in the bar except the placeholder and the model's name.
    const bar = dialog.cloneNode(true) as HTMLElement;
    bar.querySelectorAll("[popover]").forEach((list) => list.remove());
    const text = (bar.textContent ?? "").trim();
    expect(text).toBe("Demo · Default");
    for (const gone of ["BTW", "Enter", "Looking at", "inspect", "Delegate", "authorize", "read-only", "main chat"]) {
      expect(text, gone).not.toContain(gone);
    }
    expect(dialog.querySelectorAll("input[type=checkbox], [role=switch]")).toHaveLength(0);
    // The choice is one select, joined to the bar (it sits in the same form as the field).
    const select = dialog.querySelector("button[aria-label='Model that runs it']")!;
    expect(select.closest("form")).toBe(input.closest("form"));

    const setValue = (value: string) => {
      const setter = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, "value")!.set!;
      act(() => {
        setter.call(input, value);
        input.dispatchEvent(new Event("input", { bubbles: true }));
      });
    };
    setValue("What does this do?");
    // Enter in the field asks. (The model list has a search field of its own inside the same form,
    // which turns off the browser's Enter-to-submit, so the field handles Enter itself.)
    act(() => {
      input.dispatchEvent(new KeyboardEvent("keydown", { key: "Enter", bubbles: true }));
    });
    await flush();
    const start = calls.find((c) => c.cmd === "btw_start")!;
    // It asks, never edits, and runs on the chosen model (the chat's own provider by default).
    expect(start.args).toMatchObject({ mode: "ask", authorized: false, returnPolicy: "on-completion", provider: "fake", model: null });
  });

  it("the review queue lists units under the class or file that holds them, each with its reasons", async () => {
    const { ComponentQueue } = await import("../code/FileLists");
    const review = handleInsights("code_review", { checkpointId: null }, () => undefined).value as { priority: never };
    const opened: string[] = [];
    act(() =>
      root.render(
        <ComponentQueue
          activeUnit="u2"
          marks={new Map()}
          priority={review.priority}
          onOpenFile={() => undefined}
          onOpenUnit={(unit) => opened.push(unit.id)}
        />,
      ),
    );
    const text = host.textContent ?? "";
    // Components are the file or class that holds the units, never a label a model invented.
    expect(text).toContain("tokens.py");
    expect(text).toContain("DocumentRepository");
    expect(text).toContain("issue_token");
    expect(text).toContain("touches a sensitive area (`token`)");
    expect(text).toContain("signature");
    const active = host.querySelector("[aria-selected='true']");
    expect(active?.textContent).toContain("verify");
    const row = [...host.querySelectorAll("button")].find((b) => b.textContent?.includes("dispatch"))!;
    act(() => (row as HTMLButtonElement).click());
    expect(opened).toEqual(["u3"]);
  });

});
